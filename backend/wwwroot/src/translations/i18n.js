function changeLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'id';
  if (typeof state !== 'undefined' && state) {
    state.currentLang = lang;
  }
  if (typeof storeSet === 'function') storeSet(STORAGE_KEYS.lang, lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-select').forEach(sel => { sel.value = lang; });
  const t = TRANSLATIONS[lang] || TRANSLATIONS.id;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) el.innerText = t[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (t[key]) el.placeholder = t[key];
  });
  if (typeof window.applyRoute === 'function') window.applyRoute();
  else if (typeof renderAll === 'function') renderAll();
}

// Bind directly to global window scope immediately
window.changeLanguage = changeLanguage;
window.TRANSLATIONS = TRANSLATIONS;

// Format teks dengan placeholder {nama}
window.fmt = function fmt(str, vars) {
  return String(str || '').replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] !== undefined ? vars[k] : ''));
};